// Chapter: C Operators Intro

#include <stdio.h>

int main() {
    // Basic addition with operators
    int sum1 = 100 + 50;     // 150
    int sum2 = sum1 + 250;   // 400
    int sum3 = sum2 + sum2;  // 800

    printf("Sum 1: %d\n", sum1);
    printf("Sum 2: %d\n", sum2);
    printf("Sum 3: %d\n", sum3);

    return 0;
}