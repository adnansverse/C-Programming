#include <stdio.h>

int main() {
    int count = 1; // লুপ ট্র্যাকিংয়ের জন্য ভ্যারিয়েবল

    // যতক্ষণ count-এর মান 10-এর চেয়ে ছোট বা সমান থাকবে, লুপটি চলবে
    while (count <= 100) {
        printf("%d", count); // বর্তমান সংখ্যাটি প্রিন্ট করবে
        count += 2;           // মান 2 করে বাড়াবে (যেমন: 1 -> 3 -> 5...)
    }

    return 0;
}
