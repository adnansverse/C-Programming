#include <stdio.h>

int main() {
    int a;
    a = 10;
    float b;
    b = 20.5;
    char c;
    c = 'A';

    printf("Integer value: %d\n", a); // Print integer value
    printf("Float value: %.2f\n", b); // Print float value with 2 decimal places
    printf("Character value: %c\n", c); // Print character value


    return 0; // Return 0 to indicate successful execution
}